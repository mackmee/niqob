-- ==============================================================================
-- 4. AUTOMATIC USER PROFILE & FAMILY INITIALIZATION TRIGGER
-- Hardened: Does not trust raw client-provided role metadata.
-- Enforces PARENT role for self-registration, sanitizes display_name,
-- and prevents duplicate family creation.
-- ==============================================================================
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
DECLARE
    v_user_role TEXT := 'PARENT';
    v_display_name TEXT;
    v_new_family_id UUID;
BEGIN
    -- Extract and sanitize display name (trimmed, max 100 chars, fallback to email prefix)
    v_display_name := substring(
        COALESCE(
            NULLIF(trim(NEW.raw_user_meta_data->>'display_name'), ''),
            split_part(NEW.email, '@', 1),
            'Parent'
        ),
        1, 100
    );

    -- Insert into public.profiles
    INSERT INTO public.profiles (id, role, display_name)
    VALUES (NEW.id, v_user_role, v_display_name)
    ON CONFLICT (id) DO UPDATE
    SET display_name = EXCLUDED.display_name,
        updated_at = NOW();

    -- Ensure a family record exists for this parent (idempotent)
    IF NOT EXISTS (SELECT 1 FROM public.families WHERE parent_id = NEW.id) THEN
        INSERT INTO public.families (parent_id)
        VALUES (NEW.id)
        RETURNING id INTO v_new_family_id;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, extensions, pg_temp;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

