-- ------------------------------------------------------------------------------
-- Profiles: Stores user identity metadata linked directly to auth.users.
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    role TEXT NOT NULL CHECK (role IN ('PARENT', 'CHILD')),
    display_name TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ------------------------------------------------------------------------------
-- Families: Groups parent accounts and paired child devices.
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.families (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    parent_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_families_parent_id ON public.families(parent_id);

-- ------------------------------------------------------------------------------
-- Devices: Tracks parent phones & child devices within a family.
-- Minimal connectivity metadata (last_seen_at) only.
-- No personal content, message logs, or keystroke monitoring.
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.devices (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    family_id UUID NOT NULL REFERENCES public.families(id) ON DELETE CASCADE,
    user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    device_name TEXT NOT NULL,
    platform TEXT NOT NULL DEFAULT 'ANDROID' CHECK (platform IN ('ANDROID', 'IOS')),
    device_type TEXT NOT NULL DEFAULT 'CHILD_PHONE' CHECK (device_type IN ('PARENT_PHONE', 'CHILD_PHONE', 'CHILD_TABLET')),
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_devices_family_id ON public.devices(family_id);
CREATE INDEX IF NOT EXISTS idx_devices_user_id ON public.devices(user_id);

-- ------------------------------------------------------------------------------
-- Pairing Sessions: Ephemeral 10-minute pairing codes generated by parents.
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.pairing_sessions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    family_id UUID NOT NULL REFERENCES public.families(id) ON DELETE CASCADE,
    parent_device_id TEXT NOT NULL,
    child_device_id TEXT,
    pairing_code TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'CONNECTED', 'EXPIRED', 'REVOKED')),
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    connected_at TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_pairing_sessions_family_id ON public.pairing_sessions(family_id);
CREATE INDEX IF NOT EXISTS idx_pairing_sessions_code ON public.pairing_sessions(pairing_code);

-- Partial unique index: Guarantees at the database level that no two active pending
-- sessions can ever share the same pairing code simultaneously.
CREATE UNIQUE INDEX IF NOT EXISTS idx_active_pending_pairing_code
    ON public.pairing_sessions (pairing_code)
    WHERE status = 'PENDING';

-- ------------------------------------------------------------------------------
-- Screen Time Limits: Daily screen-time quota and enforcement configuration
-- per child device.
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.screen_time_limits (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    family_id UUID NOT NULL REFERENCES public.families(id) ON DELETE CASCADE,
    device_id UUID NOT NULL REFERENCES public.devices(id) ON DELETE CASCADE,
    daily_limit_minutes INT NOT NULL DEFAULT 120 CHECK (daily_limit_minutes >= 0 AND daily_limit_minutes <= 1440),
    enabled BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_screen_time_limits_device UNIQUE (device_id)
);

CREATE INDEX IF NOT EXISTS idx_screen_time_limits_family_id ON public.screen_time_limits(family_id);
CREATE INDEX IF NOT EXISTS idx_screen_time_limits_device_id ON public.screen_time_limits(device_id);

