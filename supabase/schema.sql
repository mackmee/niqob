-- ------------------------------------------------------------------------------
-- RPC: create_pairing_session
-- Called by an authenticated parent to generate a collision-free, cryptographically
-- secure 6-digit code expiring in 10 minutes.
-- ------------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.create_pairing_session(
    p_parent_device_id TEXT
)
RETURNS JSONB AS $$
DECLARE
    v_parent_uid UUID := auth.uid();
    v_family_id UUID;
    v_code TEXT;
    v_session_id UUID;
    v_expires_at TIMESTAMPTZ;
    v_attempts INT := 0;
BEGIN
    IF v_parent_uid IS NULL THEN
        RETURN jsonb_build_object(
            'success', false,
            'error_code', 'UNAUTHORIZED',
            'message', 'Authentication required. Please sign in as a parent.'
        );
    END IF;

    -- Retrieve parent's family
    SELECT id INTO v_family_id
    FROM public.families
    WHERE parent_id = v_parent_uid
    LIMIT 1;

    IF v_family_id IS NULL THEN
        INSERT INTO public.families (parent_id)
        VALUES (v_parent_uid)
        RETURNING id INTO v_family_id;
    END IF;

    -- Invalidate any existing pending sessions for this family
    UPDATE public.pairing_sessions
    SET status = 'EXPIRED'
    WHERE family_id = v_family_id AND status = 'PENDING';

    -- Generate cryptographically secure 6-digit code (100000 - 999999).
    -- Loop verifies active uniqueness across all families to prevent cross-family collisions.
    LOOP
        v_attempts := v_attempts + 1;
        v_code := ((('x' || encode(gen_random_bytes(4), 'hex'))::bit(32)::bigint % 900000) + 100000)::text;

        IF NOT EXISTS (
            SELECT 1
            FROM public.pairing_sessions
            WHERE pairing_code = v_code
              AND status = 'PENDING'
              AND expires_at > NOW()
        ) THEN
            EXIT;
        END IF;

        IF v_attempts >= 10 THEN
            RETURN jsonb_build_object(
                'success', false,
                'error_code', 'CODE_GENERATION_FAILED',
                'message', 'Failed to generate a unique pairing code. Please try again.'
            );
        END IF;
    END LOOP;

    v_expires_at := NOW() + interval '10 minutes';

    -- Insert new pending session
    INSERT INTO public.pairing_sessions (
        family_id,
        parent_device_id,
        pairing_code,
        status,
        expires_at
    ) VALUES (
        v_family_id,
        COALESCE(NULLIF(trim(p_parent_device_id), ''), 'parent_dev_unknown'),
        v_code,
        'PENDING',
        v_expires_at
    )
    RETURNING id INTO v_session_id;

    RETURN jsonb_build_object(
        'success', true,
        'session_id', v_session_id,
        'family_id', v_family_id,
        'parent_device_id', p_parent_device_id,
        'pairing_code', v_code,
        'status', 'PENDING',
        'expires_at', v_expires_at,
        'created_at', NOW()
    );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, extensions, pg_temp;

-- ------------------------------------------------------------------------------
-- RPC: pair_child_device
-- Server-side validation of pairing code with row-level locking (FOR UPDATE)
-- to prevent concurrent race conditions. Registers child device and marks
-- session CONNECTED atomically.
-- ------------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.pair_child_device(
    p_pairing_code TEXT,
    p_device_name TEXT,
    p_platform TEXT DEFAULT 'ANDROID',
    p_device_type TEXT DEFAULT 'CHILD_PHONE'
)
RETURNS JSONB AS $$
DECLARE
    v_session RECORD;
    v_device_id UUID;
    v_now TIMESTAMPTZ := NOW();
    v_existing_status TEXT;
BEGIN
    p_pairing_code := trim(p_pairing_code);

    -- Strict format check before querying
    IF length(p_pairing_code) != 6 OR p_pairing_code !~ '^\d{6}$' THEN
        RETURN jsonb_build_object(
            'success', false,
            'error_code', 'INVALID_CODE',
            'message', 'Pairing code must be a 6-digit number.'
        );
    END IF;

    -- Search strictly for active, non-expired pending session.
    -- Row-level lock (FOR UPDATE) serializes redemption and prevents race conditions.
    SELECT * INTO v_session
    FROM public.pairing_sessions
    WHERE pairing_code = p_pairing_code
      AND status = 'PENDING'
      AND expires_at > v_now
    ORDER BY created_at DESC
    LIMIT 1
    FOR UPDATE;

    IF v_session IS NULL THEN
        -- Check if an older session with this code was REVOKED, CONNECTED, or EXPIRED
        SELECT status INTO v_existing_status
        FROM public.pairing_sessions
        WHERE pairing_code = p_pairing_code
        ORDER BY created_at DESC
        LIMIT 1;

        IF v_existing_status = 'REVOKED' THEN
            RETURN jsonb_build_object(
                'success', false,
                'error_code', 'REVOKED',
                'message', 'This pairing code has been revoked by the parent.'
            );
        ELSIF v_existing_status = 'CONNECTED' THEN
            RETURN jsonb_build_object(
                'success', false,
                'error_code', 'ALREADY_USED',
                'message', 'This pairing code has already been used.'
            );
        ELSIF v_existing_status = 'EXPIRED' THEN
            RETURN jsonb_build_object(
                'success', false,
                'error_code', 'EXPIRED',
                'message', 'This pairing code has expired. Please generate a new code on the parent device.'
            );
        ELSE
            RETURN jsonb_build_object(
                'success', false,
                'error_code', 'INVALID_CODE',
                'message', 'Invalid pairing code. Please verify the code shown on the parent device.'
            );
        END IF;
    END IF;

    -- Code is valid and pending. Register child device into family.
    INSERT INTO public.devices (
        family_id,
        device_name,
        platform,
        device_type,
        last_seen_at
    ) VALUES (
        v_session.family_id,
        COALESCE(NULLIF(trim(p_device_name), ''), 'Child Device'),
        COALESCE(NULLIF(trim(p_platform), ''), 'ANDROID'),
        COALESCE(NULLIF(trim(p_device_type), ''), 'CHILD_PHONE'),
        v_now
    )
    RETURNING id INTO v_device_id;

    -- Update session to CONNECTED
    UPDATE public.pairing_sessions
    SET status = 'CONNECTED',
        child_device_id = v_device_id::text,
        connected_at = v_now
    WHERE id = v_session.id;

    RETURN jsonb_build_object(
        'success', true,
        'session_id', v_session.id,
        'family_id', v_session.family_id,
        'device_id', v_device_id,
        'device_name', COALESCE(NULLIF(trim(p_device_name), ''), 'Child Device'),
        'status', 'CONNECTED',
        'connected_at', v_now
    );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, extensions, pg_temp;

-- ------------------------------------------------------------------------------
-- RPC: update_device_heartbeat
-- Lightweight periodic heartbeat updating last_seen_at.
-- Verifies caller authorization:
-- 1. Authenticated parents can only update devices within their own family.
-- 2. Unauthenticated child callers can only update devices linked to an active,
--    connected pairing session.
-- ------------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.update_device_heartbeat(
    p_device_id UUID
)
RETURNS JSONB AS $$
DECLARE
    v_now TIMESTAMPTZ := NOW();
    v_device RECORD;
    v_caller_uid UUID := auth.uid();
BEGIN
    IF p_device_id IS NULL THEN
        RETURN jsonb_build_object(
            'success', false,
            'error_code', 'INVALID_PARAMETERS',
            'message', 'Device ID cannot be null.'
        );
    END IF;

    -- Verify device exists and retrieve parent family ownership
    SELECT d.*, f.parent_id
    INTO v_device
    FROM public.devices d
    JOIN public.families f ON f.id = d.family_id
    WHERE d.id = p_device_id;

    IF v_device IS NULL THEN
        RETURN jsonb_build_object(
            'success', false,
            'error_code', 'DEVICE_NOT_FOUND',
            'message', 'Device record not found.'
        );
    END IF;

    -- Caller authorization check
    IF v_caller_uid IS NOT NULL THEN
        IF v_device.parent_id != v_caller_uid THEN
            RETURN jsonb_build_object(
                'success', false,
                'error_code', 'UNAUTHORIZED',
                'message', 'You do not have permission to update this device.'
            );
        END IF;
    ELSE
        -- Unauthenticated child device: Must be an actively paired device in this family
        IF NOT EXISTS (
            SELECT 1
            FROM public.pairing_sessions ps
            WHERE ps.child_device_id = p_device_id::text
              AND ps.family_id = v_device.family_id
              AND ps.status = 'CONNECTED'
        ) THEN
            RETURN jsonb_build_object(
                'success', false,
                'error_code', 'UNAUTHORIZED',
                'message', 'Heartbeat rejected: device is not an active connected child device.'
            );
        END IF;
    END IF;

    -- Throttle: If last seen less than 1 second ago, return success without DB write
    IF v_device.last_seen_at >= v_now - interval '1 second' THEN
        RETURN jsonb_build_object(
            'success', true,
            'device_id', p_device_id,
            'last_seen_at', v_device.last_seen_at
        );
    END IF;

    UPDATE public.devices
    SET last_seen_at = v_now,
        updated_at = v_now
    WHERE id = p_device_id;

    RETURN jsonb_build_object(
        'success', true,
        'device_id', p_device_id,
        'last_seen_at', v_now
    );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, extensions, pg_temp;

-- ------------------------------------------------------------------------------
-- RPC: revoke_pairing_session
-- Parent revokes an active or pending pairing session.
-- Strictly validates parent ownership of the family.
-- ------------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.revoke_pairing_session(
    p_session_id UUID
)
RETURNS JSONB AS $$
DECLARE
    v_now TIMESTAMPTZ := NOW();
    v_family_id UUID;
    v_caller_uid UUID := auth.uid();
BEGIN
    IF v_caller_uid IS NULL THEN
        RETURN jsonb_build_object(
            'success', false,
            'error_code', 'UNAUTHORIZED',
            'message', 'Authentication required. Please sign in as a parent.'
        );
    END IF;

    -- Verify parent owns this family
    SELECT ps.family_id INTO v_family_id
    FROM public.pairing_sessions ps
    JOIN public.families f ON f.id = ps.family_id
    WHERE ps.id = p_session_id AND f.parent_id = v_caller_uid;

    IF v_family_id IS NULL THEN
        RETURN jsonb_build_object(
            'success', false,
            'error_code', 'UNAUTHORIZED',
            'message', 'You do not have permission to revoke this session.'
        );
    END IF;

    UPDATE public.pairing_sessions
    SET status = 'REVOKED',
        revoked_at = v_now
    WHERE id = p_session_id;

    RETURN jsonb_build_object(
        'success', true,
        'session_id', p_session_id,
        'status', 'REVOKED',
        'revoked_at', v_now
    );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, extensions, pg_temp;

